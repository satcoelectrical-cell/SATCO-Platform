def test_backend_image_installs_only_the_generated_hash_locked_requirements():
    dockerfile = (ROOT / "backend/Dockerfile.production").read_text(
        encoding="utf-8"
    )
    lock = (ROOT / "backend/requirements.production.lock").read_text(
        encoding="utf-8"
    )
    assert "COPY requirements.production.lock" in dockerfile
    assert "--require-hashes" in dockerfile
    assert "requirements.txt /app/requirements.txt" not in dockerfile
    assert "autogenerated by pip-compile with Python 3.12" in lock
    assert "pip-compile --generate-hashes" in lock
    assert lock.count("--hash=sha256:") >= 1
    assert "python:3.12-slim@sha256:" in dockerfile


def test_all_declared_production_base_images_are_digest_pinned():
    compose = (ROOT / "docker-compose.production.yml").read_text(encoding="utf-8")
    frontend = (ROOT / "frontend/Dockerfile.production").read_text(encoding="utf-8")
    assert "nginx:1.27-alpine@sha256:" in compose
    assert "postgres:17@sha256:" in compose
    assert "node:22-alpine@sha256:" in frontend
    assert "nginx:1.27-alpine@sha256:" in frontend
