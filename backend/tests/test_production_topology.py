def test_frontend_image_serves_spa_routes_on_the_internal_port():
    dockerfile = (ROOT / "frontend/Dockerfile.production").read_text(encoding="utf-8")
    config = (ROOT / "ops/nginx/frontend.conf").read_text(encoding="utf-8")
    assert "USER nginx" in dockerfile
